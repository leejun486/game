// 수련 단계 (0이면 기본 기술). 레벨이 모자라면 그 단계까지만 인정
export function rankOf(progress, cls, level, slot) {
  const E = EVOS[cls]?.[slot];
  const r = progress?.rank?.[slot] || (progress?.evo?.[slot] ? 1 : 0);
  if (!E || !r || !progress.evo?.[slot]) return 0;
  let ok = 0;
  while (ok < r && level >= E.lv[ok]) ok++;
  return ok;
}

export function branchOf(progress, cls, level, slot) {
  return rankOf(progress, cls, level, slot) ? progress.evo[slot] : null;
}

// 남은 수련점: 레벨당 1점 - 쓴 점수
export function freePoints(progress, level) {
  const used = Object.values(progress?.rank || {}).reduce((a, b) => a + b, 0);
  return Math.max(0, level - 1 - used);
}

// 단계별 위력: 피해 배수, 재사용 대기 배수
export const rankMul = (r) => 1 + 0.12 * Math.max(0, r - 1);
export const rankCd = (r) => 1 - 0.06 * Math.max(0, r - 1);
